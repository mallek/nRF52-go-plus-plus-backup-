#!/usr/bin/env python3
"""Generate pp_gachi_sprites.generated.h from sprite images.

  python tools/sprites/gen_sprites.py OUT_HEADER [--cache DIR]
  python tools/sprites/gen_sprites.py OUT_HEADER --dummy

Normal mode reads PNGs from the cache folder and downloads any that are
missing. --dummy needs no network and reads no files: it writes plain circles.
"""

import argparse
import os
import sys
import urllib.request

from PIL import Image

DEX_LIST = [1, 2, 3, 4, 5, 6, 7, 8, 9, 25, 26]
BASE_URL = "https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/"
DEFAULT_CACHE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "cache")
ALPHA_CUTOFF = 128
MAX_COLORS = 15


def rgb565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def _reduce(opaque_rgb):
    """Map each distinct opaque color to an index 1..15. Returns (colors, lookup)."""
    distinct = []
    seen = set()
    for c in opaque_rgb:
        if c not in seen:
            seen.add(c)
            distinct.append(c)
    if len(distinct) <= MAX_COLORS:
        return distinct, {c: i for i, c in enumerate(distinct)}
    print("  reducing %d colors to %d" % (len(distinct), MAX_COLORS))
    strip = Image.new("RGB", (len(distinct), 1))
    for i, c in enumerate(distinct):
        strip.putpixel((i, 0), c)
    q = strip.quantize(colors=MAX_COLORS, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    qpal = q.getpalette()
    used = sorted(set(_flat(q)))
    remap = {p: i for i, p in enumerate(used)}
    colors = [tuple(qpal[p * 3:p * 3 + 3]) for p in used]
    lookup = {c: remap[q.getpixel((i, 0))] for i, c in enumerate(distinct)}
    return colors, lookup


def _flat(im):
    getter = getattr(im, "get_flattened_data", None)
    return list(getter() if getter else im.getdata())


def pack_image(img):
    """Crop, quantize and pack. Returns (w, h, palette565_list, pixel_bytes)."""
    img = img.convert("RGBA")
    alpha = img.getchannel("A").point(lambda a: 255 if a >= ALPHA_CUTOFF else 0)
    box = alpha.getbbox()
    if box is None:
        return 1, 1, [0], bytes([0])
    img = img.crop(box)
    alpha = alpha.crop(box)
    w, h = img.size
    pixels = _flat(img)
    mask = _flat(alpha)
    opaque = [p[:3] for p, m in zip(pixels, mask) if m]
    colors, lookup = _reduce(opaque)
    palette = [0] + [rgb565(*c) for c in colors]
    stride = (w + 1) // 2
    out = bytearray(stride * h)
    for y in range(h):
        for x in range(w):
            i = y * w + x
            idx = lookup[pixels[i][:3]] + 1 if mask[i] else 0
            b = y * stride + x // 2
            if x % 2 == 0:
                out[b] |= idx << 4
            else:
                out[b] |= idx
    return w, h, palette, bytes(out)


def dummy_image(dex, shiny):
    """A 24x24 filled circle whose color comes from the dex number."""
    hue = (dex * 47) % 256
    base = ((hue * 3) % 200 + 40, (hue * 5) % 200 + 40, (hue * 7) % 200 + 40)
    if shiny:
        base = (255 - base[0] // 2, 255 - base[1] // 2, 80 + base[2] // 4)
    img = Image.new("RGBA", (24, 24), (0, 0, 0, 0))
    for y in range(24):
        for x in range(24):
            dx = x - 11.5
            dy = y - 11.5
            if dx * dx + dy * dy <= 11.0 * 11.0:
                img.putpixel((x, y), base + (255,))
    return img


def render_header(sprites, dummy=False):
    """sprites: list of (dex, shiny, (w, h, palette565, pixel_bytes))."""
    lines = []
    if dummy:
        lines.append("// DUMMY sprite table: placeholder circles, no game art.")
    else:
        lines.append("// Generated by tools/sprites/gen_sprites.py. Do not edit, do not commit.")
    lines.append("#pragma once")
    lines.append("")
    lines.append("#include <stdint.h>")
    lines.append("")
    for n, (dex, shiny, (w, h, pal, pix)) in enumerate(sprites):
        pal_text = ", ".join("0x%04X" % c for c in pal)
        pix_text = ", ".join("0x%02X" % b for b in pix)
        lines.append("static const uint16_t PP_GACHI_PAL_%d[] = {%s};" % (n, pal_text))
        lines.append("static const uint8_t PP_GACHI_PIX_%d[] = {%s};" % (n, pix_text))
    lines.append("")
    lines.append("static const PpGachiSprite PP_GACHI_SPRITE_TABLE[] = {")
    for n, (dex, shiny, (w, h, pal, pix)) in enumerate(sprites):
        lines.append("  {%d, %s, %d, %d, PP_GACHI_PAL_%d, PP_GACHI_PIX_%d},  // dex %d%s" % (
            dex, "true" if shiny else "false", w, h, n, n, dex, " shiny" if shiny else ""))
    if not sprites:
        lines.append("  {0, false, 0, 0, nullptr, nullptr},")
    lines.append("};")
    lines.append("static const uint8_t PP_GACHI_SPRITE_TABLE_COUNT = %d;" % len(sprites))
    lines.append("")
    return "\n".join(lines)


def _fetch(url):
    with urllib.request.urlopen(url, timeout=20) as r:
        return r.read()


def collect_sprites(cache_dir, fetch=_fetch):
    """Load every sprite from the cache, downloading missing ones with fetch."""
    sprites = []
    for dex in DEX_LIST:
        for shiny in (False, True):
            rel = ("shiny/%d.png" if shiny else "%d.png") % dex
            path = os.path.join(cache_dir, "shiny" if shiny else "normal", "%d.png" % dex)
            if not os.path.exists(path):
                try:
                    data = fetch(BASE_URL + rel)
                    os.makedirs(os.path.dirname(path), exist_ok=True)
                    with open(path, "wb") as f:
                        f.write(data)
                except Exception as e:
                    print("failed: %s (%s)" % (rel, e))
                    continue
            try:
                with Image.open(path) as im:
                    im.load()
                    print("packing dex %d%s" % (dex, " shiny" if shiny else ""))
                    sprites.append((dex, shiny, pack_image(im)))
            except Exception as e:
                print("failed to read %s (%s)" % (path, e))
    return sprites


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("out_header")
    ap.add_argument("--cache", default=DEFAULT_CACHE)
    ap.add_argument("--dummy", action="store_true")
    args = ap.parse_args(argv)
    if args.dummy:
        sprites = [(d, s, pack_image(dummy_image(d, s))) for d in DEX_LIST for s in (False, True)]
    else:
        sprites = collect_sprites(args.cache)
    if not sprites:
        print("no sprites written")
        return 1
    with open(args.out_header, "w", newline="\n") as f:
        f.write(render_header(sprites, dummy=args.dummy))
    print("wrote %d sprites" % len(sprites))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

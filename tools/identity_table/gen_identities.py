"""Build pp_identities.generated.h from one or more pp_device_material.<name>.h files.

The per-identity headers come from tools/flash_image_reader. This script lifts the
macro bodies out as text (it never #includes them), so the firmware can hold N
identities in one table and pick one at boot.

    python gen_identities.py OUT_HEADER NAME=PATH [NAME=PATH ...]
    python gen_identities.py OUT_HEADER --dummy TEST1 TEST2

--dummy writes fake identities (made-up MAC, zero cert/key). They advertise and
exercise the menu but can never authenticate. Safe to share.

The real output holds cert, key and MAC. CROWN JEWEL: never commit, never share.
"""

import re
import sys
from pathlib import Path

FIELDS = [
    ("PP_DEVICE_PUBLIC_ADDR_LE_BYTES", 6),
    ("PP_DEVICE_CERT_BLOCK_BYTES", 256),
    ("PP_DEVICE_SELECTOR3_BYTES", 16),
    ("PP_DEVICE_AUTH_SELECTOR4_BYTES", 16),
    ("PP_DEVICE_SELECTOR6_BYTES", 10),
]


def parse_macros(text):
    """Return {macro_name: body_text} for multi-line #define blocks."""
    macros = {}
    lines = text.splitlines()
    i = 0
    while i < len(lines):
        m = re.match(r"\s*#define\s+(\w+)\s*(.*)$", lines[i])
        if not m:
            i += 1
            continue
        name = m.group(1)
        body = [m.group(2)]
        while body[-1].rstrip().endswith("\\"):
            body[-1] = body[-1].rstrip()[:-1]
            i += 1
            body.append(lines[i])
        macros[name] = " ".join(part.strip() for part in body).strip()
        i += 1
    return macros


def byte_count(body):
    return len(re.findall(r"0x[0-9a-fA-F]{2}", body))


def mac_label(addr_body):
    le = re.findall(r"0x([0-9a-fA-F]{2})", addr_body)
    return ":".join(b.upper() for b in reversed(le))


def entry_from_header(name, path):
    macros = parse_macros(Path(path).read_text())
    if macros.get("PP_DEVICE_MATERIAL_CONFIGURED") != "1":
        sys.exit(f"{path}: PP_DEVICE_MATERIAL_CONFIGURED is not 1")
    bodies = []
    for macro, size in FIELDS:
        body = macros.get(macro)
        if body is None:
            sys.exit(f"{path}: missing {macro}")
        if byte_count(body) != size:
            sys.exit(f"{path}: {macro} has {byte_count(body)} bytes, expected {size}")
        bodies.append(body)
    return name, bodies


def dummy_entry(name, index):
    # Locally-administered style address, never a real Plus+.
    addr = "{ " + ", ".join(f"0x{b:02x}" for b in [index + 1, 0x00, 0x00, 0xad, 0xde, 0xc2]) + " }"
    zeros = lambda n: "{ " + ", ".join(["0x00"] * n) + " }"
    return name, [addr, zeros(256), zeros(16), zeros(16), zeros(10)]


def render(entries):
    out = [
        "// GENERATED by tools/identity_table/gen_identities.py - do not edit.",
        "// Holds device identities (cert, key, MAC). CROWN JEWEL: never commit, never share.",
        "#pragma once",
        "",
        '#include "pp_identity.h"',
        "",
        f"#define PP_IDENTITY_TABLE_COUNT {len(entries)}",
        "",
        "static const PpIdentity PP_IDENTITY_TABLE[PP_IDENTITY_TABLE_COUNT] = {",
    ]
    for name, bodies in entries:
        out.append("  {")
        out.append(f'    "{name}",')
        for body in bodies:
            out.append(f"    {body},")
        out.append("  },")
    out.append("};")
    out.append("")
    return "\n".join(out)


def main(argv):
    if len(argv) < 3:
        sys.exit(__doc__)
    out_path = Path(argv[1])
    args = argv[2:]
    entries = []
    if args[0] == "--dummy":
        for i, name in enumerate(args[1:]):
            entries.append(dummy_entry(name.upper(), i))
    else:
        for arg in args:
            name, _, path = arg.partition("=")
            if not path:
                sys.exit(f"bad argument '{arg}', expected NAME=PATH")
            entries.append(entry_from_header(name.upper(), path))
    if not entries:
        sys.exit("no identities given")
    for name, _ in entries:
        if len(name) > 10:
            sys.exit(f"name '{name}' is longer than 10 chars (screen width)")
    out_path.write_text(render(entries))
    for name, bodies in entries:
        print(f"  {name:<10} {mac_label(bodies[0])}")
    print(f"wrote {len(entries)} identities -> {out_path}")


if __name__ == "__main__":
    main(sys.argv)
